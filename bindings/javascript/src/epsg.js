function contains(ranges, code) {
  let low = 0;
  let high = ranges.length / 2;
  while (low < high) {
    const middle = low + Math.floor((high - low) / 2);
    const start = ranges[middle * 2];
    const end = ranges[middle * 2 + 1];
    if (code < start) high = middle;
    else if (code > end) low = middle + 1;
    else return true;
  }
  return false;
}

